import type { Hexagram, TrigramName } from '../types';

// Trigram lines [bottom, middle, top], 0=yin 1=yang — bottom-to-top ordering.
// XIANTIAN/HOUTIAN objects use the opposite (visual top-to-bottom) ordering;
// this table is only used internally to build hexagram.lines.
const TL: Record<TrigramName, [0 | 1, 0 | 1, 0 | 1]> = {
  '乾': [1, 1, 1],
  '兑': [1, 1, 0],
  '离': [1, 0, 1],
  '震': [1, 0, 0],
  '巽': [0, 1, 1],
  '坎': [0, 1, 0],
  '艮': [0, 0, 1],
  '坤': [0, 0, 0],
};

// Hexagram lines = [lower.bot, lower.mid, lower.top, upper.bot, upper.mid, upper.top]
// i.e. [line1, line2, line3, line4, line5, line6] bottom-to-top.
// lines[0..2] = lower trigram, lines[3..5] = upper trigram.
function h(
  id: number,
  name: string,
  pinyin: string,
  upper: TrigramName,
  lower: TrigramName,
): Hexagram {
  return {
    id,
    name,
    pinyin,
    lines: [...TL[lower], ...TL[upper]],
    upper,
    lower,
  };
}

